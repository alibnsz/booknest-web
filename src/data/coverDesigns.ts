function fnv1aHash(seed: string): number {
  let hash = 2166136261;
  for (let i = 0; i < seed.length; i += 1) {
    hash ^= seed.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

export function getBookCoverDesign(book: Book): BookCoverDesign {
  const preset = PRESETS[book.id];
  if (preset) {
    return preset;
  }

  const hash = fnv1aHash(`${book.id}|${book.title}|${book.author}|${book.year}`);
  const basePalette = FALLBACK_PALETTES[hash % FALLBACK_PALETTES.length];
  const layout = LAYOUT_POOL[(hash >> 3) % LAYOUT_POOL.length];
  const motif = MOTIF_POOL[(hash >> 7) % MOTIF_POOL.length];

  return {
    ...basePalette,
    layout,
    motif,
    spine: book.spineAccentColor || basePalette.spine,
  };
}
